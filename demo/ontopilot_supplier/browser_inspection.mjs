import { chromium } from '../../repos/ontopilot/frontend/node_modules/playwright-core/index.mjs'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const output = fileURLToPath(new URL('./results/', import.meta.url))
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } })
  const errors = []; let activations = 0
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().endsWith('/api/ontology/activate')) activations++ })
  await page.goto('http://127.0.0.1:8000', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: /查询员/ }).click()
  await page.locator('input[type=password]').fill('demo123')
  await page.getByRole('button', { name: '进入系统' }).click()
  await page.getByRole('button', { name: '本体配置', exact: true }).click()
  await page.getByTestId('active-ontology').getByText(/已自动加载/).waitFor()
  if (await page.getByRole('button', { name: '激活使用', exact: true }).count()) throw new Error('Redundant activation button remains')
  await page.getByRole('button', { name: '数据明细', exact: true }).click()
  await page.getByTestId('data-totals').getByText(/48 条/).waitFor()
  await page.getByRole('button', { name: '电芯受影响', exact: true }).click()
  await page.getByTestId('data-totals').getByText(/70,000/).waitFor()
  const rows = page.getByTestId('data-records').locator('tbody tr')
  if (await rows.count() !== 2) throw new Error('Expected two affected cell orders')
  await rows.filter({ hasText: 'O1' }).getByRole('button', { name: '查看 JSON' }).click()
  await page.getByTestId('record-json').getByText(/42000/).waitFor()
  await page.screenshot({ path: output + 'supplier-data-details.png', fullPage: true })
  await page.getByRole('button', { name: '华兴全部受影响', exact: true }).click()
  await page.getByTestId('data-totals').getByText(/160,000/).waitFor()
  await page.getByRole('button', { name: '全部受影响', exact: true }).click()
  await page.getByTestId('data-totals').getByText(/277,000/).waitFor()
  await page.getByRole('button', { name: '电芯全部订单', exact: true }).click()
  await page.getByTestId('data-totals').getByText(/119,000/).waitFor()
  await page.getByRole('button', { name: '本体配置', exact: true }).click()
  await page.getByTestId('active-ontology').getByText(/已自动加载/).waitFor()
  if (activations) throw new Error('Navigation activated/reset ontology')
  await page.getByRole('button', { name: '首页', exact: true }).click()
  await page.getByRole('button', { name: '开始对话', exact: true }).click()
  const question = '只看华兴科技SUP-001的电芯MAT-001：列出受延期影响的订单、件数和销售额，并解释O3为什么不受影响；评估OPT-MAT-001-FAST的额外成本和预算。只评估，不提交申请。简洁回答。'
  await page.locator('textarea').fill(question)
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/chat/live') && r.request().method() === 'POST', { timeout: 180000 })
  await page.getByRole('button', { name: '发送', exact: true }).click()
  const response = await responsePromise
  const frames = (await response.text()).split('\n\n').filter(s => s.startsWith('data: ')).map(s => JSON.parse(s.slice(6)))
  const final = frames.find(e => e.type === 'complete')
  const delay = frames.find(e => e.type === 'tool_result' && e.arguments.function_name === 'assessSupplierDelay' && e.result.affectedSalesAmount === 70000)
  const option = frames.find(e => e.type === 'tool_result' && e.arguments.function_name === 'assessSupplyOption' && e.result.extraCost === 20000)
  if (!final || !delay || !option) throw new Error('Agent did not obtain expected real function results')
  await page.getByTestId('tool-results').waitFor()
  await page.getByTestId('tool-results').locator('summary').first().click()
  const toolDetails = page.getByTestId('tool-results').locator('details').filter({ has: page.locator('summary', { hasText: /assessSupplierDelay/ }) }).first()
  await toolDetails.locator('summary').first().click()
  await toolDetails.getByText(/affectedSalesAmount/).waitFor()
  const stored = await page.request.get('http://127.0.0.1:8000/api/sessions/' + final.session_id)
  const history = (await stored.json()).session.messages.at(-1)
  if (!history.toolResults?.some(e => e.arguments.function_name === 'assessSupplierDelay' && e.result.affectedSalesAmount === 70000)) throw new Error('Actual tool result not persisted')
  await page.screenshot({ path: output + 'supplier-cell-evidence.png', fullPage: true })
  const center = page.locator('textarea')
  await center.scrollIntoViewIfNeeded()
  await page.getByTestId('tool-results').locator('summary').first().click()
  await page.getByTestId('execution-progress').last().scrollIntoViewIfNeeded()
  await page.screenshot({ path: output + 'supplier-cell-chat.png', fullPage: true })
  if (errors.length) throw new Error(errors.join('; '))
  await writeFile(output + 'inspection-browser.json', JSON.stringify({ status: 'passed', activations, question, frames, history }, null, 2))
  console.log('PASS: auto-loaded ontology after navigation, SQLite scope totals, raw JSON, real Agent tool returns and persistence; no activation required.')
} finally { await browser.close() }
